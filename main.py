@asynccontextmanager
async def lifespan(app: FastAPI):
    global yolo_session, face_app

    # ── YOLO ─────────────────────────────────────────────────────────────────
    if os.path.exists(YOLO_MODEL_PATH):
        yolo_session = ort.InferenceSession(
            YOLO_MODEL_PATH,
            providers=["CPUExecutionProvider"],
        )
        print(f"[YOLO] Loaded {YOLO_MODEL_PATH} — object detection ready.")
    else:
        print(f"[YOLO] '{YOLO_MODEL_PATH}' not found — object detection DISABLED.")

    # ── InsightFace ───────────────────────────────────────────────────────────
    try:
        from insightface.app import FaceAnalysis
        face_app = FaceAnalysis(name="buffalo_sc", providers=["CPUExecutionProvider"])
        face_app.prepare(ctx_id=-1, det_size=(320, 320))
        print("[FaceApp] InsightFace buffalo_sc ready.")
        build_face_db()
    except Exception as exc:
        print(f"[FaceApp] Load failed: {exc} — face recognition DISABLED.")

    gc.collect()
    print("[App] Startup complete. Serving requests.")
    yield
    print("[App] Shutdown.")


