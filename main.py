def cdn_upload(frame: np.ndarray, folder: str, public_id: str, quality: int = 80):
    """Encode frame as JPEG and upload to the specified Cloudinary folder."""
    ok, buf = cv2.imencode(".jpg", frame, [cv2.IMWRITE_JPEG_QUALITY, quality])
    if not ok:
        return
    try:
        cloudinary.uploader.upload(
            buf.tobytes(),
            folder=folder,
            public_id=public_id,
            resource_type="image",
        )
    except Exception as exc:
        print(f"[CDN] Upload to '{folder}/{public_id}' failed: {exc}")


