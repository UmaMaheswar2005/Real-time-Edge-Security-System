# Face recognition  — InsightFace buffalo_sc (ONNX, zero TensorFlow)
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def _norm(v: np.ndarray) -> np.ndarray:
    n = np.linalg.norm(v)
    return v / n if n > 1e-8 else v


def build_face_db() -> None:
    """
    Walk dataset/<identity_folder>/*.jpg|png
    Pre-compute L2-normalised MobileFaceNet embeddings per identity.
    Multiple identities supported — just add more sub-folders.
    """
    global admin_db
    if not os.path.exists(DATASET_DIR):
        print(f"[FaceDB] '{DATASET_DIR}' not found — create it with sub-folders of admin photos.")
        print("[FaceDB] Example:  dataset/Mahi_admin/photo1.jpg")
        return
    if face_app is None:
        return

    total_identities = 0
    for folder_name in os.listdir(DATASET_DIR):
        folder_path = os.path.join(DATASET_DIR, folder_name)
        if not os.path.isdir(folder_path):
            continue

        images = (glob.glob(os.path.join(folder_path, "*.jpg")) +
                  glob.glob(os.path.join(folder_path, "*.jpeg")) +
                  glob.glob(os.path.join(folder_path, "*.png")))

        embeddings = []
        for img_path in images:
            img = cv2.imread(img_path)
            if img is None:
                continue
            faces = face_app.get(img)
            if faces:
                embeddings.append(_norm(faces[0].embedding))

        if embeddings:
            admin_db[folder_name] = embeddings
            total_identities += 1
            print(f"[FaceDB] '{folder_name}': {len(embeddings)}/{len(images)} embeddings built.")
        else:
            print(f"[FaceDB] '{folder_name}': no faces detected in any image — skipping.")

    if total_identities == 0:
        print("[FaceDB] WARNING: No identities loaded. Add photos to dataset/ sub-folders.")
    else:
        print(f"[FaceDB] Ready with {total_identities} known identit{'y' if total_identities==1 else 'ies'}.")


def identify_faces(frame: np.ndarray) -> list[tuple[list[int], str]]:
    """
    Returns [(bbox_xyxy, identity_or_Unknown), ...] for every face in frame.
    Handles multiple people simultaneously.
    """
    if face_app is None or not admin_db:
        return []

    results = []
    for face in face_app.get(frame):
        emb = _norm(face.embedding)
        best_name, best_sim = "Unknown", -2.0

        for name, refs in admin_db.items():
            for ref_emb in refs:
                sim = float(np.dot(emb, ref_emb))
                if sim > best_sim:
                    best_sim = sim
                    if sim >= FACE_THRESHOLD:
                        best_name = name

        results.append((face.bbox.astype(int).tolist(), best_name))

    return results


def resolve_person_identity(person_box: list[int],
                            face_results: list[tuple[list[int], str]]) -> str:
    """Match a YOLO person box [x,y,w,h] to whichever face centre falls inside it."""
    px, py, pw, ph = person_box
    px2, py2 = px + pw, py + ph
    for (fx1, fy1, fx2, fy2), identity in face_results:
        if px <= (fx1+fx2)/2 <= px2 and py <= (fy1+fy2)/2 <= py2:
            return identity
    return "Unknown"


