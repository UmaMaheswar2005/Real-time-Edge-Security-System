def cdn_upload(frame: np.ndarray, folder: str, public_id: str, quality: int = 80) -> None:
    """
    JPEG-encode a BGR frame and upload it to the specified Cloudinary folder.

    Args:
        frame:     OpenCV BGR image array
        folder:    Cloudinary folder path (e.g. "surveillance/alerts")
        public_id: Filename without extension (e.g. "alert_1720000000")
        quality:   JPEG quality 1-100 (lower = smaller file, faster upload)
    """
    ok, buf = cv2.imencode(".jpg", frame, [cv2.IMWRITE_JPEG_QUALITY, quality])
    if not ok:
        print(f"[CDN] Failed to encode frame for '{folder}/{public_id}'")
        return
    try:
        cloudinary.uploader.upload(
            buf.tobytes(),
            folder=folder,
            public_id=public_id,
            resource_type="image",
        )
    except Exception as exc:
        print(f"[CDN] Upload to '{folder}/{public_id}' failed: {exc}")


