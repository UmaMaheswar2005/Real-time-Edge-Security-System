@app.get("/api/debug-cloudinary")
def debug_cloudinary():
    """
    Debug endpoint — shows exactly what Cloudinary returns for the admin_dataset folder.
    Open this in your browser if known_identities is empty.
    Tells you whether credentials are wrong, folder is empty, or path is mismatched.
    """
    try:
        result    = cloudinary.api.resources(
            type="upload",
            prefix=CDN_ADMIN_ROOT + "/",
            max_results=50,
        )
        resources = result.get("resources", [])
        # Show the raw public_ids so you can see the exact folder structure
        return {
            "status":        "ok",
            "total_found":   len(resources),
            "public_ids":    [r["public_id"] for r in resources],
            "admin_db_keys": list(admin_db.keys()),
            "cdn_admin_root": CDN_ADMIN_ROOT,
            "hint": (
                "If public_ids is empty, upload photos to Cloudinary under "
                f"'{CDN_ADMIN_ROOT}/<Your_Name>/photo.jpg'. "
                "If public_ids has entries but admin_db_keys is empty, "
                "the photos don't contain detectable faces — check photo quality."
            ),
        }
    except Exception as exc:
        return {
            "status":  "error",
            "message": str(exc),
            "hint":    "Check CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY, CLOUDINARY_API_SECRET in Render env vars.",
        }


@app.post("/api/reload-faces")
async def reload_faces():
    """
    Force a rebuild of the face embedding database from Cloudinary.
    Call this after uploading new admin photos without redeploying.
    Example: POST https://your-app.onrender.com/api/reload-faces
    """
    global admin_db
    admin_db = {}  # Clear existing database
    await asyncio.get_event_loop().run_in_executor(None, build_face_db)
    return {
        "status":           "reloaded",
        "known_identities": list(admin_db.keys()),
        "total_embeddings": {k: len(v) for k, v in admin_db.items()},
    }


@app.post("/api/analyze")
async def analyze_frame(background_tasks: BackgroundTasks, file: UploadFile = File(...)):
    """
    Main analysis endpoint — called by the frontend every ~900 ms with
    a JPEG frame captured from the webcam.

    Pipeline:
        1. Decode the uploaded JPEG frame
        2. Run YOLOv8n to detect all objects
        3. If any person is detected, run InsightFace to recognise faces
        4. Apply identity grace period to prevent label flickering
        5. Map each YOLO person box to its face identity
        6. Compute threat level: LOW / MEDIUM / HIGH
        7. Schedule Cloudinary uploads as background tasks (non-blocking)
        8. Return structured JSON to the frontend immediately

    Cloudinary uploads are offloaded to background threads via BackgroundTasks
    so they never block the event loop or freeze the camera feed.

    Returns:
        {
            "identity":       str,          # name of recognised admin or "Unknown"
            "objects":        [...],        # list of detected objects with labels and boxes
            "threat_level":   str,          # "LOW", "MEDIUM", or "HIGH"
            "threat_objects": [str, ...],   # names of weapon-class objects detected
        }
    """
    global _last_snapshot, _last_alert, _last_identity, _last_match_time

    # Decode uploaded JPEG bytes into an OpenCV BGR frame
    raw   = await file.read()
    arr   = np.frombuffer(raw, np.uint8)
    frame = cv2.imdecode(arr, cv2.IMREAD_COLOR)
    if frame is None:
        return {"error": "Invalid image — could not decode the uploaded frame."}

    now = time.time()

    # ── Step 1: Object detection ──────────────────────────────────────────────
    detections  = yolo_detect(frame)
    person_dets = [d for d in detections if d["label"] == "person"]
    threat_dets = [d for d in detections if d["threat"]]

    # ── Step 2: Face recognition (only when at least one person is detected) ──
    face_results  = []
    identity_name = "Unknown"
    any_known     = False

    if person_dets:
        face_results = identify_faces(frame)

        # Check if any face in this frame matched a known identity
        for _, name in face_results:
            if name != "Unknown":
                _last_identity   = name
                _last_match_time = now
                any_known        = True
                break  # one confirmed match is enough to mark the frame

        # Grace period: if no match this frame but we had one recently,
        # carry the last identity forward to avoid flickering labels
        if not any_known and (now - _last_match_time) < IDENTITY_GRACE:
            if _last_identity != "Unknown":
                # Inject a virtual face entry so person boxes get labelled correctly
                face_results = [([0, 0, 1, 1], _last_identity)] + face_results
                any_known    = True

        identity_name  = _last_identity if any_known else "Unknown"
        _last_identity = identity_name

    else:
        # No person in frame — reset identity (grace period does not apply
        # when there is literally nobody visible)
        _last_identity = "Unknown"
        identity_name  = "Unknown"

    # ── Step 3: Per-person labelling ──────────────────────────────────────────
    # Each YOLO detection keeps its original label except "person" boxes,
    # which get labelled with the matched identity or "Unknown Human".
    objects = []
    for d in detections:
        label = d["label"]
        if label == "person":
            pid   = resolve_person_identity(d["box"], face_results)
            label = f"Admin: {pid}" if pid != "Unknown" else "Unknown Human"
        objects.append({"label": label, "box": d["box"], "threat": d["threat"]})

    # ── Step 4: Threat level scoring ──────────────────────────────────────────
    unknown_intruder = any(o["label"] == "Unknown Human" for o in objects)
    if threat_dets:
        threat_level = "HIGH"     # weapon-class object detected
    elif unknown_intruder:
        threat_level = "MEDIUM"   # unrecognised person detected
    else:
        threat_level = "LOW"      # only known admins or no people

    # ── Step 5: Cloudinary DVR uploads ────────────────────────────────────────
    # Both uploads are scheduled as background tasks so they run AFTER the
    # response is already sent to the frontend. This means the camera feed
    # never freezes waiting for a Cloudinary network call to finish.

    # 5-A: Routine heartbeat — one frame every SNAPSHOT_INTERVAL seconds
    if now - _last_snapshot >= SNAPSHOT_INTERVAL:
        background_tasks.add_task(cdn_upload, frame, CDN_ROUTINE, f"frame_{int(now)}", 70)
        _last_snapshot = now

    # 5-B: Alert snapshot — triggered by unknown intruder or weapon detection.
    # ALERT_COOLDOWN prevents duplicate uploads for the same ongoing event.
    if (unknown_intruder or threat_dets) and (now - _last_alert >= ALERT_COOLDOWN):
        alert_frame = frame.copy()
        # Red border for weapons, orange for unknown intruder
        color = (0, 0, 255) if threat_dets else (0, 140, 255)
        cv2.rectangle(alert_frame, (0, 0), (alert_frame.shape[1], alert_frame.shape[0]), color, 10)
        msg = "WEAPON DETECTED" if threat_dets else "UNKNOWN INTRUDER"
        cv2.putText(alert_frame, f"ALERT: {msg}", (20, 56),
                    cv2.FONT_HERSHEY_DUPLEX, 1.2, color, 2)

        folder = CDN_WEAPONS if threat_dets else CDN_ALERTS
        background_tasks.add_task(cdn_upload, alert_frame, folder, f"alert_{int(now)}", 85)
        _last_alert = now

    return {
        "identity":       identity_name,
        "objects":        objects,
        "threat_level":   threat_level,
        "threat_objects": [d["label"] for d in threat_dets],
    }


@app.post("/api/gemini")
def ask_gemini(file: UploadFile = File(...)):
    """
    On-demand Gemini AI analysis endpoint — called when the user clicks
    "Ask Gemini AI" in the frontend.

    This is intentionally a synchronous (non-async) endpoint. FastAPI
    automatically runs sync endpoints in a thread pool, keeping the main
    event loop free during the Gemini network call (which can take 5-10 s).
    Making it async would block the event loop and cause health check
    timeouts, making Render think the service is offline.

    Model selection: first tries to dynamically list models available to
    your specific API key (avoids 404s from deprecated model names), then
    falls back to the hardcoded GEMINI_MODELS list if the listing fails.

    Returns:
        {
            "response":   str,        # Gemini's analysis text
            "model_used": str | None, # which model succeeded, or None on failure
        }
    """
    if not gemini_client:
        return {"response": "Gemini API key not configured.", "model_used": None}

    # Sync file read — required because this endpoint is no longer async
    raw     = file.file.read()
    pil_img = Image.open(io.BytesIO(raw)).convert("RGB")

    # Dynamically discover which flash models are available to this API key.
    # This prevents 404 errors caused by Google deprecating model names over time.
    # NOTE: the API returns names as "models/gemini-2.5-flash" — we must strip
    # the "models/" prefix before passing to generate_content, otherwise every
    # call fails with a 404.
    # Falls back to the hardcoded GEMINI_MODELS list if the listing API fails.
    try:
        active_models = []
        for m in gemini_client.models.list():
            supports = getattr(m, "supported_generation_methods", [])
            if "generateContent" in supports and "flash" in m.name:
                # Strip the "models/" prefix that the list API includes
                clean_name = m.name.replace("models/", "")
                active_models.append(clean_name)
        if not active_models:
            raise ValueError("No flash models returned by listing API")
        print(f"[Gemini] Available flash models: {active_models}")
    except Exception as exc:
        print(f"[Gemini] Model listing failed ({exc}) — using fallback list.")
        active_models = GEMINI_MODELS

    last_err = None
    for model_name in active_models:
        try:
            resp = gemini_client.models.generate_content(
                model=model_name,
                contents=[SECURITY_PROMPT, pil_img],
            )
            if resp and resp.text:
                return {"response": resp.text.strip(), "model_used": model_name}
        except Exception as exc:
            print(f"[Gemini] '{model_name}' failed: {exc}")
            last_err = exc

    return {
        "response":   f"All Gemini models unavailable. Last error: {last_err}",
        "model_used": None,
    }