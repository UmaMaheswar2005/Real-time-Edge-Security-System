# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    FastAPI lifespan context — runs startup code before the first request
    and teardown code after the last.

    Load order:
        1. Configure Cloudinary (credentials from env)
        2. Load YOLOv8n ONNX session
        3. Load InsightFace buffalo_sc models
        4. Fetch admin photos from Cloudinary and build embedding database
        5. Free build-time memory with gc.collect()
    """
    global yolo_session, face_app

    # ── 1. Cloudinary — configure inside lifespan so .env is already loaded ──
    cloudinary.config(
        cloud_name=os.getenv("CLOUDINARY_CLOUD_NAME"),
        api_key=os.getenv("CLOUDINARY_API_KEY"),
        api_secret=os.getenv("CLOUDINARY_API_SECRET"),
    )

    # ── 2. YOLO ───────────────────────────────────────────────────────────────
    # yolov8n.onnx is copied into the image by the Docker builder stage.
    # On local dev: run `python export_onnx.py` once to generate it.
    if os.path.exists(YOLO_MODEL_PATH):
        yolo_session = ort.InferenceSession(
            YOLO_MODEL_PATH,
            providers=["CPUExecutionProvider"],
        )
        print(f"[YOLO] yolov8n.onnx loaded — object detection ready.")
    else:
        print(f"[YOLO] '{YOLO_MODEL_PATH}' not found — object detection DISABLED.")
        print("[YOLO] Run: python export_onnx.py  (requires: pip install ultralytics)")

    # ── 3. InsightFace ────────────────────────────────────────────────────────
    # buffalo_sc is pre-downloaded into the Docker image by prebake_insightface.py.
    # On local dev: first run auto-downloads ~67 MB of ONNX models to
    # ~/.insightface/models/buffalo_sc/ — this is cached for subsequent runs.
    try:
        from insightface.app import FaceAnalysis
        face_app = FaceAnalysis(name="buffalo_sc", providers=["CPUExecutionProvider"])
        face_app.prepare(ctx_id=-1, det_size=(320, 320))
        print("[FaceApp] InsightFace buffalo_sc loaded — face recognition ready.")

        # ── 4. Build face embedding database from Cloudinary photos ──────────
        # Run in a thread executor because build_face_db makes blocking
        # network calls (Cloudinary API + photo downloads) that would
        # stall the async event loop if called directly.
        await asyncio.get_event_loop().run_in_executor(None, build_face_db)

    except Exception as exc:
        print(f"[FaceApp] Failed to load InsightFace: {exc}")
        print("[FaceApp] Face recognition DISABLED.")

    # ── 5. Release build-time allocations before serving requests ─────────────
    gc.collect()
    print("[App] Startup complete — serving requests.")

    yield   # ← application runs here, handling HTTP requests

    print("[App] Shutdown — goodbye.")


