# Face recognition — InsightFace buffalo_sc (ONNX, zero TensorFlow)
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def _norm(v: np.ndarray) -> np.ndarray:
    """L2-normalise a vector. Returns the zero vector unchanged if norm ≈ 0."""
    n = np.linalg.norm(v)
    return v / n if n > 1e-8 else v


def build_face_db() -> None:
    """
    Download admin photos from Cloudinary at startup and build a face
    embedding database in memory.

    Cloudinary layout expected:
        admin_dataset/
            Mahi_admin/       ← sub-folder name becomes the identity label
                photo1.jpg
                photo2.jpg
                ...
            Another_Person/
                photo1.jpg

    Photos are downloaded via HTTPS, decoded with OpenCV, and processed by
    InsightFace to extract MobileFaceNet embeddings. Raw image bytes are
    discarded immediately — nothing is written to disk.

    To add a new person   → create a new sub-folder in Cloudinary + redeploy.
    To remove a person    → delete their Cloudinary sub-folder + redeploy.
    To update photos      → replace photos in Cloudinary + redeploy.
    Redeploy via          → Render dashboard → Manual Deploy.
    """
    global admin_db

    if face_app is None:
        print("[FaceDB] FaceApp not loaded — skipping database build.")
        return

    print(f"[FaceDB] Listing photos in Cloudinary '{CDN_ADMIN_ROOT}/'...")

    try:
        result    = cloudinary.api.resources(
            type="upload",
            prefix=CDN_ADMIN_ROOT + "/",
            max_results=500,         # increase if you have > 500 admin photos total
        )
        resources = result.get("resources", [])
    except Exception as exc:
        print(f"[FaceDB] Cloudinary API error: {exc}")
        print("[FaceDB] Check CLOUDINARY_* environment variables in Render dashboard.")
        return

    if not resources:
        print(f"[FaceDB] No photos found under Cloudinary '{CDN_ADMIN_ROOT}/'.")
        print("[FaceDB] Upload photos to Cloudinary → admin_dataset/<Your_Name>/photo.jpg")
        return

    # Group photo URLs by identity name (the sub-folder directly under admin_dataset/)
    # e.g. public_id "admin_dataset/Mahi_admin/photo1" → identity "Mahi_admin"
    identity_map: dict[str, list[str]] = {}
    for res in resources:
        parts = res["public_id"].split("/")
        if len(parts) < 3:
            continue                      # ignore files placed directly in admin_dataset/
        identity_name = parts[1]          # "Mahi_admin"
        identity_map.setdefault(identity_name, []).append(res["secure_url"])

    if not identity_map:
        print("[FaceDB] No identity sub-folders found.")
        print("[FaceDB] Photos must be at: admin_dataset/<Name>/<photo>.jpg")
        return

    total_loaded = 0
    for identity_name, urls in identity_map.items():
        embeddings = []
        for url in urls:
            try:
                # Download photo bytes directly into memory — no temp files
                with urllib.request.urlopen(url, timeout=10) as resp:
                    img_bytes = resp.read()
                img_array = np.frombuffer(img_bytes, np.uint8)
                img = cv2.imdecode(img_array, cv2.IMREAD_COLOR)
                if img is None:
                    continue
                faces = face_app.get(img)
                if faces:
                    # Use the largest detected face (most likely the subject)
                    largest = max(faces, key=lambda f: (f.bbox[2]-f.bbox[0]) * (f.bbox[3]-f.bbox[1]))
                    embeddings.append(_norm(largest.embedding))
            except Exception as exc:
                print(f"[FaceDB]   ✗ {url.split('/')[-1]}: {exc}")
                continue

        if embeddings:
            admin_db[identity_name] = embeddings
            total_loaded += 1
            print(f"[FaceDB]   ✓ '{identity_name}': {len(embeddings)}/{len(urls)} embeddings built.")
        else:
            print(f"[FaceDB]   ✗ '{identity_name}': no faces detected in any photo — skipping.")

    if total_loaded == 0:
        print("[FaceDB] WARNING: No identities loaded. Verify photos contain visible faces.")
    else:
        suffix = "y" if total_loaded == 1 else "ies"
        print(f"[FaceDB] Ready — {total_loaded} known identit{suffix}: {list(admin_db.keys())}")


def identify_faces(frame: np.ndarray) -> list[tuple[list[int], str]]:
    """
    Detect all faces in a BGR frame and match each one against admin_db.

    Returns a list of (bbox, identity) tuples:
        bbox     → [x1, y1, x2, y2] in pixel coordinates
        identity → matched identity name, or "Unknown" if no match above threshold

    Supports multiple people in frame simultaneously — each face is matched
    independently against all known identities.
    """
    if face_app is None or not admin_db:
        return []

    results = []
    for face in face_app.get(frame):
        emb = _norm(face.embedding)
        best_name = "Unknown"
        best_sim  = -2.0    # cosine similarity range is [-1, 1]

        for name, refs in admin_db.items():
            for ref_emb in refs:
                # Dot product of two L2-normalised vectors = cosine similarity
                sim = float(np.dot(emb, ref_emb))
                if sim > best_sim:
                    best_sim = sim
                    if sim >= FACE_THRESHOLD:
                        best_name = name

        results.append((face.bbox.astype(int).tolist(), best_name))

    return results


def resolve_person_identity(
    person_box: list[int],
    face_results: list[tuple[list[int], str]],
) -> str:
    """
    Map a single YOLO person box [x, y, w, h] to an identity by finding
    the face whose centre-point lies inside the person bounding box.

    Returns the matched identity name or "Unknown" if no face centre
    falls inside the box (e.g. person detected but face not visible).
    """
    px, py, pw, ph = person_box
    px2, py2 = px + pw, py + ph

    for (fx1, fy1, fx2, fy2), identity in face_results:
        face_cx = (fx1 + fx2) / 2
        face_cy = (fy1 + fy2) / 2
        if px <= face_cx <= px2 and py <= face_cy <= py2:
            return identity

    return "Unknown"


